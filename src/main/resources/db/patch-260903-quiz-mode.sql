-- 260903 "틀린 문제 다시 풀기" 2회차부터 즉시 채점 — 제출 모드 기록
--
-- 두 번째 다시 풀기부터는 보기를 고르는 즉시 정답/오답을 보여줘야 한다(키독 방식). 그러려면
-- "이 학생이 이 책의 이 난이도를 틀린 문제만 다시 푼 게 지금까지 몇 번인지"를 셀 수 있어야 하는데,
-- 지금은 제출이 어떤 모드였는지(첫 제출 / 재도전 / 틀린 문제만)가 어디에도 남지 않는다.
-- submitted_at이 같으면 같은 회차이므로(ddl-core.sql 주석 참고) 모드까지 있으면
-- COUNT(DISTINCT submitted_at)로 모드별 회차 수를 셀 수 있다.
-- ============================================================================

-- FIRST(첫 제출) / RETRY(재도전) / WRONG_ONLY(틀린 문제만 다시 풀기)
-- 값 자체가 최대 10자라 VARCHAR(10). 이 패치 이전 기록은 NULL로 남는다(모드를 알 수 없음) —
-- 회차 계산은 WRONG_ONLY만 세므로 NULL이 섞여도 결과가 틀어지지 않는다.
IF COL_LENGTH('erp_bookstore_quiz_answer_log', 'submit_mode') IS NULL
    ALTER TABLE erp_bookstore_quiz_answer_log
        ADD submit_mode VARCHAR(10) NULL;
GO
